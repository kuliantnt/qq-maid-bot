#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) struct TextBlock {
    pub(super) original: &'static str,
    pub(super) translation: &'static str,
    pub(super) note: &'static str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct SpecialText {
    pub(super) label: &'static str,
    pub(super) text: TextBlock,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct HexagramText {
    pub(super) code: u8,
    pub(super) number: u8,
    pub(super) short_name: &'static str,
    pub(super) full_name: &'static str,
    pub(super) gua: TextBlock,
    pub(super) lines: [TextBlock; 6],
    pub(super) special: Option<SpecialText>,
}

const fn text(original: &'static str, translation: &'static str, note: &'static str) -> TextBlock {
    TextBlock {
        original,
        translation,
        note,
    }
}

const fn special(
    label: &'static str,
    original: &'static str,
    translation: &'static str,
    note: &'static str,
) -> SpecialText {
    SpecialText {
        label,
        text: text(original, translation, note),
    }
}

